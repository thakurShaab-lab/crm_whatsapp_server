export function getIsdFromMobile(mobile) {
  let isdCode = ''
  for (let i = 4; i >= 1; i--) {
    const prefix = mobile.slice(0, i)
    if (ISD_CODES.includes(prefix)) {
      isdCode = prefix
    }
  }
  return isdCode
}
